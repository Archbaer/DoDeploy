const sgSection = (ir: EnrichedIR): string => {
  const names = new Set([
    ...ir.compute.map((u) => u.name),
    ...ir.datastores.map((d) => d.name),
    ...ir.network.securityGroupRules.flatMap((r) => [r.from, r.to]),
  ]);
  const groups = [...names]
    .map(
      (name) => `resource "aws_security_group" "service_${tfName(name)}" {
  name_prefix = ${quote(`service_${tfName(name)}-`)}
  vpc_id = aws_vpc.main.id
  egress {
    from_port = 0
    to_port = 0
    protocol = "-1"
    cidr_blocks = ["0.0.0.0/0"]
  }
}`,
    )
    .join("\n\n");
  const ingress = [
    ...publicRoutes(ir).map(({ unit, port }) => ({
      from: "alb",
      to: `service_${tfName(unit.name)}`,
      port: port.container,
    })),
    ...ir.network.securityGroupRules.map((r) => ({
      from: `service_${tfName(r.from)}`,
      to: `service_${tfName(r.to)}`,
      port: r.port,
    })),
  ];
  const uniqueIngress = [
    ...new Map(ingress.map((r) => [`${r.from}|${r.to}|${r.port}`, r])).values(),
  ];
  return `${groups}\n\n${uniqueIngress
    .map(
      (rule, index) => `resource "aws_security_group_rule" "ingress_${index}" {
  type = "ingress"
  from_port = ${rule.port}
  to_port = ${rule.port}
  protocol = "tcp"
  source_security_group_id = aws_security_group.${rule.from}.id
  security_group_id = aws_security_group.${rule.to}.id
}`,
    )
    .join("\n\n")}`;
};

