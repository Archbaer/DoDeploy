const taskDefSection = (ir: EnrichedIR): string => {
  const units = fargateUnits(ir);
  if (units.length === 0) return "";
  return units
    .map((u) => {
      const label = tfName(u.name);
      const { cpu, memory } = fargateSize(u);
      const portMappings =
        u.ports.length > 0
          ? `      portMappings = [${u.ports
              .filter(
                (port, index) =>
                  u.ports.findIndex(
                    (other) =>
                      other.container === port.container && other.protocol === port.protocol,
                  ) === index,
              )
              .map((p) => `{ containerPort = ${p.container}, protocol = ${quote(p.protocol)} }`)
              .join(", ")}]`
          : "";
      const envVars = Object.entries(u.env)
        .filter(([key]) => !u.secrets.includes(key))
        .map(([key, value]) => `        { name = ${quote(key)}, value = ${quote(value)} },`)
        .join("\n");
      const environment = envVars.length > 0 ? `      environment = [\n${envVars}\n      ]` : "";
      const commandEntry = [
        u.entrypoint !== undefined
          ? `      entryPoint = [${u.entrypoint.map(quote).join(", ")}]`
          : "",
        u.command !== undefined ? `      command    = [${u.command.map(quote).join(", ")}]` : "",
      ]
        .filter(Boolean)
        .join("\n");
      const secretTodo = u.secrets
        .map(
          (key) =>
            `# TODO(dodeploy): ${JSON.stringify(u.name)} secret ${JSON.stringify(key)}: create a Secrets Manager secret manually, add its ARN through container secrets name/valueFrom, and grant the ECS task execution role secretsmanager:GetSecretValue (and kms:Decrypt when required).`,
        )
        .join("\n");
      return `${secretTodo}${secretTodo ? "\n" : ""}resource "aws_ecs_task_definition" "${label}" {
  family                   = ${quote(label)}
  requires_compatibilities = ["FARGATE"]
  network_mode             = "awsvpc"
  execution_role_arn = aws_iam_role.ecs_execution.arn
  cpu                      = "${cpu}"
  memory                   = "${memory}"
  container_definitions    = jsonencode([
    {
      name      = ${quote(label)}
      image     = ${unitImage(u)}
      essential = true
${commandEntry ? `${commandEntry}\n` : ""}${portMappings}
${environment}
    }
  ])
}`;
    })
    .join("\n\n");
};
